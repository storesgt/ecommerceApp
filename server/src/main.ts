import 'dotenv/config';
import cors from 'cors';
import express from 'express';
import helmet from 'helmet';
import path from 'node:path';
import { prisma } from './lib/prisma';
import { errorHandler } from './middleware/errors';
import authRouter from './modules/auth';
import productsRouter from './modules/products';
import ordersRouter from './modules/orders';
import paymentsRouter from './modules/payments';
import cartRouter from './modules/cart';
import wishlistRouter from './modules/wishlist';
import addressesRouter from './modules/addresses';
import reviewsRouter from './modules/reviews';
import couponsRouter from './modules/coupons';
import shippingRouter from './modules/shipping';
import taxesRouter from './modules/taxes';
import usersRouter from './modules/users';
import analyticsRouter from './modules/analytics';
import auditRouter from './modules/audit';
import notificationsRouter from './modules/notifications';
import refundsRouter from './modules/refunds';
import catalogRouter from './modules/catalog';
import mediaRouter from './modules/media';
import settingsRouter from './modules/settings';
import chatRouter from './modules/chat';
import { rateLimit } from './middleware/rate-limit';
import { openapi } from './openapi';
import { recordActivity } from './middleware/activity-log';

const app = express();
const port = Number(process.env.PORT || 4000);

app.disable('etag');
app.use((_, response, next) => {
  response.setHeader('Cache-Control', 'no-store, no-cache, must-revalidate, proxy-revalidate');
  response.setHeader('Pragma', 'no-cache');
  response.setHeader('Expires', '0');
  next();
});
app.use(helmet({ crossOriginResourcePolicy: { policy: 'cross-origin' }, contentSecurityPolicy: { directives: { imgSrc: ["'self'", 'data:', 'https://images.unsplash.com'] } } }));
app.use(cors({ origin: process.env.CORS_ORIGIN?.split(',') || true }));
app.use(express.json({ limit: '1mb', verify: (request, _response, buffer) => { (request as typeof request & { rawBody?: Buffer }).rawBody = Buffer.from(buffer); } }));
app.use('/uploads', express.static(path.resolve(process.cwd(), 'uploads')));
app.use(express.static(path.resolve(process.cwd())));
app.get('/favicon.ico', (_request, response) => response.sendFile(path.resolve(process.cwd(), 'favicon.svg')));
app.use(recordActivity);
app.get('/', (_request, response) => response.sendFile(path.resolve(process.cwd(), 'index.html')));
app.get('/index.html', (_request, response) => response.sendFile(path.resolve(process.cwd(), 'index.html')));
app.get('/api-docs.json', (_request, response) => response.json(openapi));
app.get('/health', async (_request, response) => { await prisma.$queryRaw`SELECT 1`; response.json({ status: 'ok', service: 'ground-api' }); });
app.use('/api/v1/auth', rateLimit(20, 15 * 60 * 1000), authRouter);
app.use('/api/v1/products', productsRouter);
app.use('/api/v1/orders', ordersRouter);
app.use('/api/v1/payments', rateLimit(60, 60 * 1000), paymentsRouter);
app.use('/api/v1/cart', cartRouter);
app.use('/api/v1/wishlist', wishlistRouter);
app.use('/api/v1/addresses', addressesRouter);
app.use('/api/v1/reviews', reviewsRouter);
app.use('/api/v1/coupons', couponsRouter);
app.use('/api/v1/shipping', shippingRouter);
app.use('/api/v1/taxes', taxesRouter);
app.use('/api/v1/users', usersRouter);
app.use('/api/v1/analytics', analyticsRouter);
app.use('/api/v1/audit-logs', auditRouter);
app.use('/api/v1/notifications', notificationsRouter);
app.use('/api/v1/refunds', refundsRouter);
app.use('/api/v1/catalog', catalogRouter);
app.use('/api/v1/media', mediaRouter);
app.use('/api/v1/settings', settingsRouter);
app.use('/api/v1/chat', chatRouter);
app.use(errorHandler);

const server = app.listen(port, () => console.log(`Ground API listening on http://localhost:${port}`));

async function shutdown(signal: string) { console.log(`${signal}: shutting down`); await prisma.$disconnect(); server.close(() => process.exit(0)); }
process.on('SIGINT', () => void shutdown('SIGINT'));
process.on('SIGTERM', () => void shutdown('SIGTERM'));
